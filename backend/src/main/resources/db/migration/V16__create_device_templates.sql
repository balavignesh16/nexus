CREATE TABLE device_templates (
    id UUID PRIMARY KEY,
    template_key VARCHAR(100) NOT NULL UNIQUE,
    display_name VARCHAR(150) NOT NULL,
    description TEXT,
    manufacturer VARCHAR(100),
    model VARCHAR(100),
    protocol_type VARCHAR(20) NOT NULL CHECK (protocol_type IN ('MQTT')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_device_templates_key CHECK (template_key ~ '^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$')
);

CREATE TABLE device_template_capabilities (
    id UUID PRIMARY KEY,
    template_id UUID NOT NULL REFERENCES device_templates(id) ON DELETE CASCADE,
    capability_definition_id UUID NOT NULL REFERENCES capability_definitions(id) ON DELETE RESTRICT,
    required BOOLEAN NOT NULL DEFAULT TRUE,
    default_unit VARCHAR(50),
    display_order INTEGER NOT NULL DEFAULT 0,
    freshness_threshold_seconds INTEGER,
    configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT uk_template_capability UNIQUE (template_id, capability_definition_id),
    CONSTRAINT ck_template_freshness CHECK (freshness_threshold_seconds IS NULL OR freshness_threshold_seconds > 0)
);

